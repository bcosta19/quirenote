#!/usr/bin/env python3
"""Turns bench raw.json (run_bench.py) into the markdown tables of RESULTS.md: median over the
repetitions, with the (min-max) spread of the headline numbers.

    aggregate.py /tmp/qbench/results/raw.json > tables.md
"""
import json
import statistics
import sys
from collections import defaultdict

raw = json.load(open(sys.argv[1]))
SERVERS = ["go", "rs"]
NAMES = {"go": "Go", "rs": "Rust"}

by = defaultdict(list)  # (label, server) -> [result, ...]
for r in raw:
    by[(r["label"], r["name"])].append(r)
reps = max(len(v) for v in by.values())


def get(r, path):
    for p in path.split("."):
        if isinstance(r, dict) and p in r:
            r = r[p]
        else:
            return None
    return r


def values(label, server, path):
    scale = 1024 if path.endswith("_kb") else 1  # kB -> MB
    vals = [get(r, path) for r in by[(label, server)]]
    return [v / scale for v in vals if isinstance(v, (int, float))]


def med(label, server, path):
    vals = values(label, server, path)
    return statistics.median(vals) if vals else None


def rng(label, server, path):
    vals = values(label, server, path)
    return (min(vals), max(vals)) if vals else (None, None)


def f(v, d=1, unit=""):
    if v is None:
        return "-"
    if abs(v) >= 1000 and d <= 1:
        return f"{v:,.0f}{unit}"
    return f"{v:.{d}f}{unit}"


def cell(label, server, path, d=1, unit="", spread=True):
    m = med(label, server, path)
    lo, hi = rng(label, server, path)
    if m is None:
        return "-"
    s = f(m, d, unit)
    if spread and lo is not None and (hi - lo) > 0 and reps > 1:
        s += f" ({f(lo, d)}-{f(hi, d)})"
    return s


def mb(label, server, path):
    return med(label, server, path)


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def side(title, label_list, metrics, note=""):
    """metrics: [(column title, path, decimals, unit)]; one row per (label, metric-set), both servers."""
    headers = ["case", "server"] + [m[0] for m in metrics]
    rows = []
    for label in label_list:
        for s in SERVERS:
            if (label, s) not in by:
                continue
            rows.append([label, NAMES[s]] + [cell(label, s, m[1], m[2], m[3]) for m in metrics])
    return f"### {title}\n\n" + (note + "\n\n" if note else "") + table(headers, rows) + "\n"


print(f"<!-- generated by bench/aggregate.py from {sys.argv[1]}; {reps} repetitions, median (min-max) -->\n")

# ---- 1. same note ----------------------------------------------------------------------
print(side("1a. Concurrent saves of the SAME version of one note (all N clients hold the version they read)",
           ["conflict-50", "conflict-200", "conflict-1000"],
           [("accepted", "accepted", 0, ""), ("rejected 409", "rejected_409", 0, ""), ("other status", "other_status", 0, ""),
            ("transport errors", "transport_errors", 0, ""), ("lost updates", "lost_updates", 0, ""),
            ("tmp files left", "leftover_tmp", 0, ""), ("wall ms", "wall_ms", 0, ""), ("p50 ms", "latency.p50_ms", 0, ""),
            ("p99 ms", "latency.p99_ms", 0, ""), ("server CPU s", "server.cpu_s", 2, ""), ("peak RSS MB", "server.vmhwm_kb", 1, "")],
           "Each client sends a 64 KiB body that carries its own id in every 1 KiB line, so truncation or interleaving would be detectable."))
integ = []
for label in ["conflict-50", "conflict-200", "conflict-1000"]:
    for s in SERVERS:
        vals = [r.get("integrity") for r in by[(label, s)]]
        integ.append([label, NAMES[s], "; ".join(sorted(set(map(str, vals)))), f"{sum(1 for v in vals if v == 'ok')}/{len(vals)}"])
print("Integrity verdict of the final file (it must be exactly one accepted client's content):\n")
print(table(["case", "server", "verdict(s) seen", "runs ok"], integ) + "\n")

print(side("1b. Read-modify-write on one note (each worker GETs, appends a unique line, PUTs with the mtime it read; 409 = retry)",
           ["rmw-50x10", "rmw-200x5", "rmw-1000x2"],
           [("accepted", "accepted", 0, ""), ("409s", "rejected_409", 0, ""), ("lines on disk", "lines_on_disk", 0, ""),
            ("LOST updates", "lost_updates", 0, ""), ("wall ms", "wall_ms", 0, ""), ("server CPU s", "server.cpu_s", 1, ""),
            ("peak RSS MB", "server.vmhwm_kb", 1, ""), ("tmp left", "leftover_tmp", 0, "")],
           "Every accepted write must survive: lines on disk = accepted. A shortfall is a lost update."))

# ---- 2. different notes -----------------------------------------------------------------
print(side("2. Concurrent saves of DIFFERENT notes (64 clients, 4 KiB, 10 s, each with the mtime of its previous response)",
           ["writes-64"],
           [("req/s", "rps", 0, ""), ("p50 ms", "latency.p50_ms", 2, ""), ("p95 ms", "latency.p95_ms", 2, ""),
            ("p99 ms", "latency.p99_ms", 2, ""), ("non-200", "non_200", 0, ""), ("transport errors", "transport_errors", 0, ""),
            ("server CPU s", "server.cpu_s", 1, "")]))
# CPU per request
rows = []
for s in SERVERS:
    ok = med("writes-64", s, "ok")
    cpu = med("writes-64", s, "server.cpu_s")
    if ok:
        rows.append([NAMES[s], f(ok, 0), f(cpu, 1), f(cpu / ok * 1000, 3)])
print(table(["server", "requests ok", "CPU s", "CPU ms per request"], rows) + "\n")

# ---- 3. reads ----------------------------------------------------------------------------
print(side("3. Reads on the large vault (10,000 notes, 1,114 folders)",
           ["read-note", "read-tree", "read-search", "read-backlinks"],
           [("clients", "clients", 0, ""), ("req/s", "rps", 0, ""), ("p50 ms", "latency.p50_ms", 2, ""), ("p95 ms", "latency.p95_ms", 2, ""),
            ("p99 ms", "latency.p99_ms", 2, ""), ("avg body B", "avg_resp_bytes", 0, ""), ("non-200", "non_200", 0, ""),
            ("transport err", "transport_errors", 0, ""), ("server CPU s", "server.cpu_s", 1, ""), ("rg children CPU s", "server.child_cpu_s", 1, ""),
            ("peak RSS MB", "server.vmhwm_kb", 1, "")],
           "10 s measured after a 2 s warm-up. Search and backlinks run `rg` as a child process in both servers (its CPU is in the children column)."))

# ---- 4. memory ----------------------------------------------------------------------------
rows = []
for label in ["startup-small", "startup-large"]:
    for s in SERVERS:
        rows.append([label, NAMES[s], f(mb(label, s, "server.rss_idle_kb"), 1), f(mb(label, s, "server.vmhwm_kb"), 1),
                     cell(label, s, "server.threads_before", 0, "")])
print("### 4a. Memory at rest (RSS 1.5 s after the start, MB)\n")
print(table(["vault", "server", "idle RSS MB", "peak RSS (VmHWM) MB", "threads"], rows) + "\n")

labels = ["conflict-50", "conflict-200", "conflict-1000", "rmw-50x10", "rmw-200x5", "rmw-1000x2", "writes-64", "read-note", "read-tree", "read-search", "read-backlinks", "sse-500", "sse-2000", "consistency"]
rows = []
for label in labels:
    for s in SERVERS:
        if (label, s) not in by:
            continue
        rows.append([label, NAMES[s], f(mb(label, s, "server.rss_idle_kb"), 1), f(mb(label, s, "server.vmhwm_kb"), 1), f(mb(label, s, "server.rss_end_kb"), 1),
                     f(mb(label, s, "server.rss_3s_after_kb"), 1), cell(label, s, "server.threads_after", 0, "", False)])
print("### 4b. Memory in each scenario (fresh process per run: peak = VmHWM at the end; MB)\n")
print(table(["scenario", "server", "idle RSS", "PEAK (VmHWM)", "RSS right after", "RSS 3 s after", "threads after"], rows) + "\n")

# ---- 5. SSE --------------------------------------------------------------------------------
print("### 5. SSE fan-out (K clients on /api/events, 20 external changes written to the vault by rename; latency = write done -> LAST client received)\n")
rows = []
for label in ["sse-500", "sse-2000"]:
    for s in SERVERS:
        rows.append([label, NAMES[s], cell(label, s, "connected", 0, "", False), cell(label, s, "connect_failed", 0, "", False),
                     cell(label, s, "events_all_delivered", 0, "", False), cell(label, s, "events_partial", 0, "", False), cell(label, s, "events_missed", 0, "", False),
                     cell(label, s, "latency_until_all_received.p50_ms", 1, ""), cell(label, s, "latency_until_all_received.max_ms", 1, ""),
                     cell(label, s, "bytes_per_connection", 0, ""), cell(label, s, "threads_connected", 0, "", False),
                     f(mb(label, s, "server.rss_idle_kb"), 1), f(mb(label, s, "rss_kb_connected"), 1), f(mb(label, s, "server.vmhwm_kb"), 1),
                     cell(label, s, "server.cpu_s", 2, "", False)])
print(table(["case", "server", "connected", "failed", "events delivered to all", "partial", "missed", "latency p50 ms", "latency max ms", "bytes/conn (RSS)", "threads",
             "RSS idle MB", "RSS w/ conns MB", "peak MB", "CPU s"], rows) + "\n")

# ---- 6. consistency ------------------------------------------------------------------------
print("### 6. Concurrent trash / move / relink (correctness; passes out of runs)\n")
names = []
for r in raw:
    if r["label"] == "consistency":
        for c in r["checks"]:
            if c["name"] not in names:
                names.append(c["name"])
rows = []
for n in names:
    row = [n]
    for s in SERVERS:
        runs = by[("consistency", s)]
        ok = sum(1 for r in runs if any(c["name"] == n and c["ok"] for c in r["checks"]))
        details = sorted({c["detail"] for r in runs for c in r["checks"] if c["name"] == n and not c["ok"]})
        row.append(f"{ok}/{len(runs)}" + (f" ({'; '.join(details)[:90]})" if details else ""))
    rows.append(row)
print(table(["check", "Go", "Rust"], rows) + "\n")

# ---- 7. startup ----------------------------------------------------------------------------
print("### 7. Start time (process spawn -> first answer; polled every 2 ms; page cache warm)\n")
rows = []
for label in ["startup-small", "startup-large"]:
    for s in SERVERS:
        rows.append([label.replace("startup-", ""), NAMES[s], cell(label, s, "server.listen_ms", 1, ""), cell(label, s, "server.first_tree_ms", 1, "")])
print(table(["vault", "server", "first answer (`/api/setup` 200) ms", "first `GET /api/tree` 200 ms"], rows) + "\n")
